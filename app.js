function page(id, button) {
    var pages = document.getElementsByClassName("page");
    for (var i = 0; i < pages.length; i++) {
        pages[i].classList.remove("active");
    }

    var targetPage = document.getElementById(id);
    if (targetPage) {
        targetPage.classList.add("active");
    }

    var buttons = document.querySelectorAll(".menu button");
    for (var j = 0; j < buttons.length; j++) {
        buttons[j].classList.remove("active");
    }

    if (button) {
        button.classList.add("active");
    }

    var titles = {
        'doc-dashboard': ["Doctor Dashboard", "Your clinical workspace & live triage queue"],
        'doc-triage': ["Triage Priority Queue", "AI urgency prioritization (P1 / P2 / P3)"],
        'doc-newcase': ["New Clinical Case", "Voice, OCR & AI structured case intake"],
        'doc-patients': ["Patient Registry", "Search longitudinal patient histories"],
        'doc-ai': ["AI Assistant Suite", "Clinical decision support & red-flags"],
        'pat-dashboard': ["Patient Health Home", "Your prescriptions, timeline & self-intake"],
        'pat-intake': ["Submit Symptoms & First-Aid", "Preliminary advice & doctor priority queue"],
        'pat-records': ["My Prescriptions", "Active medicines and past consultation slips"],
        'pat-timeline': ["Health Timeline", "Complete history of your medical visits"]
    };

    if (titles[id]) {
        document.getElementById("topTitle").innerHTML = titles[id][0];
        document.getElementById("topSubtitle").innerHTML = titles[id][1];
    }

    if (id === "doc-patients") displayPatients('doc');
    if (id === "pat-records") displayPatients('pat');
    if (id === "doc-triage") renderTriageQueue();
}

function savePatient(prefix) {
    var isPat = (prefix === 'pat');
    var name = document.getElementById(isPat ? "patName" : "name").value;
    var age = document.getElementById(isPat ? "patAge" : "age").value;
    var gender = document.getElementById(isPat ? "patGender" : "gender").value;
    var phone = document.getElementById(isPat ? "patPhone" : "phone").value;
    var symptoms = document.getElementById(isPat ? "patSymptoms" : "symptoms").value;
    var duration = document.getElementById(isPat ? "patDuration" : "duration").value;
    var severity = document.getElementById(isPat ? "patSeverity" : "severity").value;
    var history = document.getElementById(isPat ? "patHistory" : "history").value;
    var medications = document.getElementById(isPat ? "patMeds" : "medications").value;
    var allergies = document.getElementById(isPat ? "patAllergies" : "allergies").value;

    if (name === "" || age === "" || symptoms === "") {
        alert("Please enter Name, Age and Symptoms.");
        return;
    }

    var aiAnalysis = generateAI(prefix);

    var patient = {
        id: "MC-" + (patients.length + 101),
        name: name,
        age: age,
        gender: gender,
        phone: phone,
        symptoms: symptoms,
        duration: duration,
        severity: severity,
        triageLevel: aiAnalysis.triageLevel,
        history: history,
        medications: medications,
        allergies: allergies,
        status: (aiAnalysis.isEmergency || !history) ? "Needs Review" : "Completed",
        aiSummary: aiAnalysis.structuredSummary,
        date: new Date().toLocaleDateString()
    };

    patients.unshift(patient);
    saveState();

    alert(isPat 
        ? "✓ Symptoms submitted! You have been placed in the Doctor Priority Queue (" + aiAnalysis.triageLevel + ")." 
        : "✓ Clinical case saved to patient registry with Triage Level (" + aiAnalysis.triageLevel + ")!"
    );

    updateDashboard();

    if (isPat) {
        page('pat-records');
    } else {
        page('doc-triage');
    }
}

